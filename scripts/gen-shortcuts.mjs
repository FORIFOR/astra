#!/usr/bin/env node
/**
 * §20 のショートカット表を Rust の定数へ生成する。
 *
 * Global shortcut は Rust が登録し、面のショートカットは TypeScript が受ける。
 * 同じ表を両側が手で持つと、「設定で変えたのに OS 側は古いまま」になる。
 * TypeScript を正として生成し、CI で鮮度を検査する（geometry と同じ扱い）。
 *
 *   node scripts/gen-shortcuts.mjs [--check]
 */
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
import { SHORTCUTS } from '../packages/ui-kit/dist/index.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = path.join(root, 'apps/desktop/src-tauri/src/shortcut_generated.rs');

/** Rust の `#[cfg]` に合わせた OS の分け方。 */
const PLATFORMS = [
  { key: 'macos', cfg: 'target_os = "macos"' },
  { key: 'windows', cfg: 'target_os = "windows"' },
  { key: 'linux', cfg: 'not(any(target_os = "macos", target_os = "windows"))' },
];

/** ui-kit の Modifiers を tauri の Modifiers 式にする。 */
function modifiers(m, platform) {
  const parts = [];
  if (m.control) parts.push('Modifiers::CONTROL');
  if (m.alt) parts.push('Modifiers::ALT');
  if (m.shift) parts.push('Modifiers::SHIFT');
  // macOS の primary は Command（tauri では SUPER）
  if (m.primary) parts.push(platform === 'macos' ? 'Modifiers::SUPER' : 'Modifiers::CONTROL');
  // bitflags の `|` は const 文脈で呼べない。const fn の bits() を経由する。
  if (parts.length === 0) return 'None';
  const bits = parts.map((p) => `${p}.bits()`).join(' | ');
  return `Some(Modifiers::from_bits_truncate(${bits}))`;
}

const binding = (b, platform) =>
  `Binding { modifiers: ${modifiers(b.modifiers, platform)}, code: Code::${b.code}, label: "${b.code}" }`;

const global = SHORTCUTS.filter((s) => s.scope === 'global');

const perPlatform = PLATFORMS.map(({ key, cfg }) => {
  const rows = global
    .map(
      (s) => `    GlobalShortcutSpec {
        id: "${s.id}",
        label: "${s.label}",
        hold: ${s.hold},
        default_binding: ${binding(s.defaults[key], key)},
        alternates: &[${s.alternates[key].map((a) => binding(a, key)).join(', ')}],
    },`,
    )
    .join('\n');
  return `#[cfg(${cfg})]
pub const GLOBAL_SHORTCUTS: &[GlobalShortcutSpec] = &[
${rows}
];`;
}).join('\n\n');

const body = `// @generated by scripts/gen-shortcuts.mjs — do not edit.
//
// 正は packages/ui-kit/src/shortcuts.ts（UI/UX §20）。
// 表を変えるときはそちらを直して \`pnpm gen:shortcuts\` を実行する。

use tauri_plugin_global_shortcut::{Code, Modifiers, Shortcut};

/// 1 つの割り当て。
#[derive(Debug, Clone, Copy)]
pub struct Binding {
    pub modifiers: Option<Modifiers>,
    pub code: Code,
    /// TypeScript 側と突き合わせるための \`KeyboardEvent.code\`。
    pub label: &'static str,
}

impl Binding {
    pub fn shortcut(self) -> Shortcut {
        Shortcut::new(self.modifiers, self.code)
    }
}

/// OS 全体で効くショートカット（UI/UX §20 の global 行）。
#[derive(Debug, Clone, Copy)]
pub struct GlobalShortcutSpec {
    pub id: &'static str,
    pub label: &'static str,
    /// 押している間だけ効くもの（push-to-talk）。
    pub hold: bool,
    pub default_binding: Binding,
    /// 既定が OS / IME に取られているときに薦める順の候補。
    pub alternates: &'static [Binding],
}

${perPlatform}
`;

async function formatted(source) {
  const dir = await mkdtemp(path.join(tmpdir(), 'astra-gen-'));
  const file = path.join(dir, 'shortcut_generated.rs');
  try {
    await writeFile(file, source);
    await run('rustfmt', ['--edition', '2021', file]);
    return await readFile(file, 'utf8');
  } catch {
    console.warn('rustfmt is unavailable; writing the unformatted output');
    return source;
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const output = await formatted(body);

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== output) {
    console.error(`FAIL: ${path.relative(root, target)} is stale. Run: pnpm gen:shortcuts`);
    process.exit(1);
  }
  console.log('shortcut table is current');
} else {
  await writeFile(target, output);
  console.log(`wrote ${path.relative(root, target)}`);
}
