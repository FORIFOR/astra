#!/usr/bin/env node
// Keep the MIT shader and the user's preset identical in the native and web clients.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = (p) => readFile(new URL(p, root), 'utf8');
const preset = JSON.parse(await read('shared/design/liquid-orb/preset.json'));
const keys = [
  'speed',
  'radius',
  'zoom',
  'warp',
  'ridgeAmt',
  'sharp',
  'shade',
  'sheen',
  'gloss',
  'shellMidAlpha',
  'shellEdgeAlpha',
  'exposure',
  'style',
  'edgeSoftness',
  'edgeGlow',
  'paletteCount',
  'glassEnabled',
  'glassOpacity',
  'contourDeform',
  'bandDensity',
  'chromaticShift',
  'metalScale',
  'metalStretch',
  'metalAngle',
  'metalOffset',
  'metalPhase',
  'metalEvolution',
  'metalRoughness',
  'metalDepth',
  'particleDensity',
  'ribbonCount',
  'ribbonWidth',
  'ribbonTwist',
  'ribbonFold',
  'ribbonBreath',
  'particleSize',
  'particleBloom',
];
const colors = [
  'colorA',
  'colorB',
  'colorC',
  'colorD',
  'highlightColor',
  'shellInner',
  'shellMid',
  'shellEdge',
  'sheenColor',
  'specColor',
  'canvasColor',
  'glowColor',
];
const palette = [
  '#F7FBFF',
  '#EFF6FD',
  '#E0EEF9',
  '#D4E6F7',
  '#BBD5F3',
  '#A6C7F0',
  '#87B0EB',
  ...Array(5).fill('#6F9EE8'),
];
function seed(p) {
  const rgb = (s) => [...[1, 3, 5].map((i) => parseInt(s.slice(i, i + 2), 16) / 255), 1];
  return [
    1,
    1,
    0,
    ...keys.map((k) => p[k]),
    ...[...colors.map((k) => p[k]), ...palette].flatMap(rgb),
  ];
}
const sourceModule = await read('shared/design/liquid-orb/shader-source.ts');
const entryPoints = sourceModule.match(/const vertexAndFragment = `([\s\S]*?)`;/)?.[1];
if (!entryPoints) throw Error('Upstream WGSL entry points missing');
const webShader = (await read('shared/design/liquid-orb/effect.wgsl')) + '\n' + entryPoints;
const fallback = (await readFile(new URL('shared/design/liquid-orb/fallback.png', root))).toString(
  'base64',
);
const license = await read('shared/design/liquid-orb/LICENSE');
const banner =
  '// Generated by scripts/gen-liquid-orb.mjs; do not edit.\n// ' +
  license.trim().replaceAll('\n', '\n// ').replaceAll('\n// \n', '\n//\n') +
  '\n';
const seeds = { idle: seed(preset.idle), active: seed(preset.active) };
if (seeds.idle.length !== 136 || seeds.active.some((x) => !Number.isFinite(x)))
  throw Error('Invalid orb uniform layout');
const swift =
  banner +
  '\nimport Foundation\n\nenum LiquidOrbAssets {\n    static let activation: Double = ' +
  preset.activation +
  '\n    static let settle: Double = ' +
  preset.settle +
  '\n' +
  Object.entries(seeds)
    .map(
      ([k, v]) =>
        '    static let ' +
        k +
        ': [Float] = [\n' +
        Array.from(
          { length: 17 },
          (_, i) => '        ' + v.slice(i * 8, i * 8 + 8).join(', ') + ',',
        ).join('\n') +
        '\n    ]\n',
    )
    .join('') +
  '    static let fallbackPNG = Data(base64Encoded: "' +
  fallback +
  '")!\n' +
  '    static let metal = #"""\n' +
  (await read('shared/design/liquid-orb/effect.metal')) +
  '\n"""#\n}\n';
const ts =
  banner +
  '\nexport const orbActivation = ' +
  preset.activation +
  ';\nexport const orbSettle = ' +
  preset.settle +
  ';\nexport const orbSeeds = ' +
  JSON.stringify(seeds) +
  ';\nexport const orbFallback = ' +
  JSON.stringify('data:image/png;base64,' + fallback) +
  ';\nexport const orbShader = ' +
  JSON.stringify(webShader) +
  ';\n';
for (const [path, content] of [
  ['apps/genie-macos/Sources/GenieMac/Components/LiquidOrbAssets.swift', swift],
  ['apps/desktop/src/voice/liquid-orb/generated.ts', ts],
]) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if ((await readFile(url, 'utf8')) !== content) throw Error('Stale ' + path);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
console.log('LIQUID_ORB_ASSETS_OK');
