#!/usr/bin/env node
/**
 * Dock の geometry を Rust の定数へ生成する。
 *
 * 同じ数字を TypeScript と Rust の両方が使う（CSS と window サイズ）。
 * 手で二重に持つとずれるので、TypeScript を正として生成し、
 * CI で鮮度を検査する（schema.sql と同じ扱い）。
 *
 *   node scripts/gen-dock-geometry.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { dockGeometry, dockPlacement, DOCK_STATES } from '../packages/ui-kit/dist/index.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = path.join(root, 'apps/desktop/src-tauri/src/dock/geometry_generated.rs');

const variant = (state) => state.charAt(0).toUpperCase() + state.slice(1);

const body = `// @generated by scripts/gen-dock-geometry.mjs — do not edit.
//
// 正は packages/ui-kit/src/tokens/dock.ts（UI/UX §4.1・§4.2）。
// 値を変えるときはそちらを直して \`pnpm gen:dock-geometry\` を実行する。

/// Dock が形を変える状態（UI/UX §3・§4.1）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DockState {
${DOCK_STATES.map((s) => `    ${variant(s)},`).join('\n')}
}

/// window のサイズ。高さは内容に応じて min..=max の範囲で決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DockSize {
    pub width: u32,
    pub min_height: u32,
    pub max_height: u32,
}

impl DockState {
    pub fn size(self) -> DockSize {
        match self {
${DOCK_STATES.map((s) => {
  const g = dockGeometry[s];
  return `            DockState::${variant(s)} => DockSize { width: ${g.width}, min_height: ${g.minHeight}, max_height: ${g.maxHeight} },`;
}).join('\n')}
        }
    }
}

/// 画面下端からの距離（UI/UX §4.2）。
pub const BOTTOM_OFFSET_MIN: i32 = ${dockPlacement.bottomOffsetMin};
pub const BOTTOM_OFFSET_MAX: i32 = ${dockPlacement.bottomOffsetMax};
pub const BOTTOM_OFFSET_DEFAULT: i32 = ${dockPlacement.bottomOffsetDefault};
/// 画面端に寄せすぎないための余白。
pub const EDGE_MARGIN: i32 = ${dockPlacement.edgeMargin};
`;

const check = process.argv.includes('--check');
if (check) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== body) {
    console.error(`FAIL: ${path.relative(root, target)} is stale. Run: pnpm gen:dock-geometry`);
    process.exit(1);
  }
  console.log('dock geometry constants are current');
} else {
  await writeFile(target, body);
  console.log(`wrote ${path.relative(root, target)}`);
}
