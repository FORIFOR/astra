#!/usr/bin/env node
// Recording Workspace の外枠（上辺中央に凹み）を、shared/design/tokens.json から
// 正準の SVG パスとして生成する。macOS(RecordingWorkspaceShape) と Windows
// (RecordingWorkspaceGeometry) は同じ制御点でこの形を描く。両 OS の実装が
// この golden と一致することを visual regression fixture として担保する（§5・§6）。
//
//   node scripts/gen-workspace-fixture.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(ROOT, 'shared/design/tokens.json'), 'utf8'));
const w = tokens.recordingWorkspace;
const W = w.width, H = w.height, r = w.cornerRadius;
const nW = w.notchWidth, depth = w.notchDepth, shoulder = w.notchShoulder;
const cx = W / 2, nL = cx - nW / 2, nR = cx + nW / 2;

// Swift/WinUI と同一の制御点（固定オフセット 14/15）で d を組む。
const n = (x) => (Number.isInteger(x) ? String(x) : x.toFixed(2));
const d = [
  `M ${n(r)},0`,
  `L ${n(nL - shoulder)},0`,
  `C ${n(nL - 14)},0 ${n(nL - 15)},${n(depth)} ${n(nL)},${n(depth)}`,
  `L ${n(nR)},${n(depth)}`,
  `C ${n(nR + 15)},${n(depth)} ${n(nR + 14)},0 ${n(nR + shoulder)},0`,
  `L ${n(W - r)},0`,
  `Q ${n(W)},0 ${n(W)},${n(r)}`,
  `L ${n(W)},${n(H - r)}`,
  `Q ${n(W)},${n(H)} ${n(W - r)},${n(H)}`,
  `L ${n(r)},${n(H)}`,
  `Q 0,${n(H)} 0,${n(H - r)}`,
  `L 0,${n(r)}`,
  `Q 0,0 ${n(r)},0`,
  'Z',
].join(' ');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- @generated by scripts/gen-workspace-fixture.mjs from shared/design/tokens.json — do not edit. -->
  <path d="${d}" fill="#1c1c1e"/>
</svg>
`;

const target = resolve(ROOT, 'shared/design/fixtures/recording-workspace.svg');
const check = process.argv.includes('--check');
if (check) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (current !== svg) {
    console.error('recording-workspace fixture is stale — run `node scripts/gen-workspace-fixture.mjs`');
    process.exit(1);
  }
  console.log('recording-workspace fixture is current');
} else {
  writeFileSync(target, svg);
  console.log(`wrote ${target}`);
}

// Swift/C# の実装から検証できるよう、正準の d を単独でも出す（fixture の隣に）。
const dTarget = resolve(ROOT, 'shared/design/fixtures/recording-workspace.path');
if (check) {
  let cur = '';
  try { cur = readFileSync(dTarget, 'utf8'); } catch { /* */ }
  if (cur.trim() !== d) { console.error('recording-workspace.path is stale'); process.exit(1); }
} else {
  writeFileSync(dTarget, d + '\n');
}
